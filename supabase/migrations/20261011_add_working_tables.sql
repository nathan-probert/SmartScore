-- Working set: the day's lean player/team slices, persisted at the end of the
-- first_run pipeline so normal_run/last_run can skip the GetPlayers sub-machine
-- (32+ NHL API calls) without reloading the denormalized Picks table.
--
-- The denormalized Picks rows duplicate ~10 opp_goalie_* fields and team stats
-- onto every skater; carrying them through Step Functions hit the 256KB state
-- limit (States.DataLimitExceeded in the pipeline's GetDate). These tables
-- store the same separated slices the in-flight first_run state already uses:
-- one lean player dict and one team dict per row, joined on team_id inside the
-- Lambdas, never denormalized.
--
-- `data` is JSONB rather than a fixed column list on purpose: this is internal
-- staging whose shape tracks the lean pipeline payload (stat, tims, injury and
-- lineup fields have all been added over time and will be again). A column
-- list here would need a migration for every payload change. The frontend
-- never reads these tables; the published Picks rows are unchanged.
--
-- The identity `id` column exists only so the shared Supabase writer's wipe
-- step (`DELETE ... WHERE id <> 0`) works, matching Picks/Historic-Picks. It
-- is not part of any join: players join teams on the `team_id` stored inside
-- the JSONB payload, keyed per (date, player_id) / (date, team_id).
--
-- Like Picks/Historic-Picks there is deliberately no RLS: the anon-key
-- pipeline client reads and writes these tables, and the rows carry nothing
-- the public Picks table does not already expose. Player-Snapshots is the
-- one table that keeps RLS (admin client only).
--
-- All statements are idempotent because .github/workflows/deploy.yml pipes
-- every file in this directory through psql on every deploy with no migration
-- history.

CREATE TABLE IF NOT EXISTS "Working-Players-__ENV__" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "date" TEXT NOT NULL,
    "player_id" BIGINT NOT NULL,
    "data" JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS "Working-Teams-__ENV__" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "date" TEXT NOT NULL,
    "team_id" BIGINT NOT NULL,
    "data" JSONB NOT NULL
);
