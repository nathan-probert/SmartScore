-- Working-Goalies: the day's starting-goalie slice, staged by MakePredictions
-- and GetTims alongside Working-Players/Working-Teams (see
-- 20261011_add_working_tables.sql).
--
-- The enrichment tail (GetTims -> SaveToDb -> UpdateHistory -> PublishToDb)
-- now re-reads the slices inside the Lambdas instead of round-tripping the
-- fully enriched roster through Step Functions state, which hit the 256KB
-- limit on heavy slates (15-game days). Goalies are the slice the original
-- working tables never stored.
--
-- Rows are keyed per (date, team_id) because the denormalizer joins goalies
-- to players through numeric team_id (one starter per team). Starters whose
-- abbreviation is not on today's slate carry no team_id and are not staged --
-- the DB join ignores them anyway.
--
-- A ``None`` goalie slice (failed fetch) skips this table entirely, so the
-- writer's full-table wipe does not erase the day's previously staged rows.
--
-- Like the other Working-* tables there is deliberately no RLS: the anon-key
-- pipeline client reads and writes these rows, which carry nothing the
-- published Picks rows do not already expose. The frontend never reads them.
--
-- All statements are idempotent because .github/workflows/deploy.yml pipes
-- every file in this directory through psql on every deploy with no migration
-- history.

CREATE TABLE IF NOT EXISTS "Working-Goalies-__ENV__" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "date" TEXT NOT NULL,
    "team_id" BIGINT NOT NULL,
    "data" JSONB NOT NULL
);
